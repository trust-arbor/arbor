  # -- decide_start/1 (behavior matrix) -------------------------------------

  defp host_intent(tag \\ :auto, host \\ "127.0.0.1"), do: {tag, host}

  describe "decide_start/1" do
    test "fresh install: no metadata, no legacy pid -> proceed" do
      facts = %{metadata: :absent, legacy_pid_present?: false, host_intent: host_intent()}
      assert {:proceed, "127.0.0.1"} = Identity.decide_start(facts)
    end

    test "legacy daemon verified alive -> refuses (legacy daemons block start)" do
      facts = %{
        metadata: :absent,
        legacy_pid_present?: true,
        legacy_pid_check: {:verified_arbor, @node},
        host_intent: host_intent()
      }

      assert {:refuse, :legacy_daemon_alive, %{node: @node}} = Identity.decide_start(facts)
    end

    test "legacy pid stale (dead) -> proceeds" do
      facts = %{
        metadata: :absent,
        legacy_pid_present?: true,
        legacy_pid_check: :no_such_process,
        host_intent: host_intent()
      }

      assert {:proceed, "127.0.0.1"} = Identity.decide_start(facts)
    end

    test "legacy pid reused by an unrelated process -> proceeds" do
      facts = %{
        metadata: :absent,
        legacy_pid_present?: true,
        legacy_pid_check: :present_not_arbor,
        host_intent: host_intent()
      }

      assert {:proceed, "127.0.0.1"} = Identity.decide_start(facts)
    end

    test "legacy pid liveness unverified -> refuses ambiguously" do
      facts = %{
        metadata: :absent,
        legacy_pid_present?: true,
        legacy_pid_check: :unverified,
        host_intent: host_intent()
      }

      assert {:refuse, :ambiguous_legacy_state, %{}} = Identity.decide_start(facts)
    end

    test "malformed metadata -> refuses and never proceeds (never treated as absent)" do
      facts = %{metadata: {:error, :malformed}, host_intent: host_intent()}
      assert {:refuse, :malformed_metadata, %{}} = Identity.decide_start(facts)
    end

    test "valid metadata, pid verified match -> refuses already_running" do
      meta = %{node: @node, host: "127.0.0.1", pid: 42, state: :ready}

      facts = %{
        metadata: {:ok, meta},
        metadata_pid_check: {:verified_arbor, @node},
        host_intent: host_intent()
      }

      assert {:refuse, :already_running, %{node: @node, pid: 42}} = Identity.decide_start(facts)
    end

    test "valid metadata, pid verified but names a different node -> refuses node_identity_mismatch" do
      meta = %{node: @node, host: "127.0.0.1", pid: 42, state: :ready}

      facts = %{
        metadata: {:ok, meta},
        metadata_pid_check: {:verified_arbor, @other_node},
        host_intent: host_intent()
      }

      assert {:refuse, :node_identity_mismatch, %{expected: @node, observed: @other_node}} =
               Identity.decide_start(facts)
    end

    test "valid metadata, pid ambiguous -> refuses ambiguous_metadata_pid" do
      meta = %{node: @node, host: "127.0.0.1", pid: 42, state: :ready}

      facts = %{
        metadata: {:ok, meta},
        metadata_pid_check: :unverified,
        host_intent: host_intent()
      }

      assert {:refuse, :ambiguous_metadata_pid, %{}} = Identity.decide_start(facts)
    end

    test "valid metadata, pid stale -> proceeds (stale metadata safe to overwrite)" do
      meta = %{node: @node, host: "127.0.0.1", pid: 42, state: :ready}

      facts = %{
        metadata: {:ok, meta},
        metadata_pid_check: :no_such_process,
        host_intent: host_intent(:auto, "10.42.42.103")
      }

      assert {:proceed, "10.42.42.103"} = Identity.decide_start(facts)
    end

    test "host drift without an explicit override, persisted node verified alive -> refuses (the incident)" do
      # Reproduces the reported incident directly: metadata was written for
      # 127.0.0.1, the interface-detected host has since drifted to
      # 10.42.42.103, and no operator override is set. Naively recomputing
      # the node from the freshly detected host (the pre-fix behavior) would
      # never even ask this question; here the persisted node is checked and
      # found verified-alive, so start refuses instead of spawning a
      # duplicate.
      meta = %{node: @node, host: "127.0.0.1", pid: 42, state: :ready}

      facts = %{
        metadata: {:ok, meta},
        metadata_pid_check: {:verified_arbor, @node},
        host_intent: host_intent(:auto, "10.42.42.103")
      }

      assert {:refuse, :already_running, _} = Identity.decide_start(facts)
    end

    test "explicit relocation while the old host is verified alive -> refuses (must stop first)" do
      meta = %{node: @node, host: "127.0.0.1", pid: 42, state: :ready}

      facts = %{
        metadata: {:ok, meta},
        metadata_pid_check: {:verified_arbor, @node},
        host_intent: host_intent(:operator_relocation, "10.42.42.103")
      }

      assert {:refuse, :already_running, _} = Identity.decide_start(facts)
    end

    test "explicit relocation once the old host is confirmed dead -> proceeds at the new host" do
      meta = %{node: @node, host: "127.0.0.1", pid: 42, state: :ready}

      facts = %{
        metadata: {:ok, meta},
        metadata_pid_check: :no_such_process,
        host_intent: host_intent(:operator_relocation, "10.42.42.103")
      }

      assert {:proceed, "10.42.42.103"} = Identity.decide_start(facts)
    end

    test "restart continuity host is honored when no operator override is present" do
      facts = %{
        metadata: :absent,
        legacy_pid_present?: false,
        host_intent: host_intent(:internal_continuity, "127.0.0.1")
      }

      assert {:proceed, "127.0.0.1"} = Identity.decide_start(facts)
    end
  end

