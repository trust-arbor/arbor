  # -- Helpers.acquire_lock/1 stale-lock fail-closed behavior ----------------

  describe "Helpers.acquire_lock/1 stale-lock fail-closed behavior" do
    # Linux's largest configurable pid_max is 4_194_304 (the value itself is
    # not allocated), while Darwin's limit is lower. This remains inside the
    # lifecycle record's accepted bound but cannot identify a live process.
    @dead_pid 4_194_304

    defp stage_stale_lock(home) do
      refute Config.pid_alive?(@dead_pid)

      dir = Config.lock_dir(home)
      File.mkdir_p!(dir)

      File.write!(
        Path.join(dir, "owner.json"),
        Identity.encode_lock_owner(@dead_pid, "stale-token")
      )

      dir
    end

    test "security regression: a delayed stale contender cannot remove a replacement lock" do
      home = tmp_home()
      dir = stage_stale_lock(home)

      assert {:refuse, :stale_lock, %{pid: @dead_pid}} = Config.acquire_lock(home)
      assert File.dir?(dir)

      # Simulate explicit operator recovery, then a new command acquiring a
      # fresh generation. A delayed contender has no stale-reclaim primitive
      # to invoke: it must re-observe the live owner and leave the token intact.
      File.rm_rf!(dir)
      assert {:ok, token} = Config.acquire_lock(home)
      owner_before = File.read!(Path.join(dir, "owner.json"))

      assert {:refuse, :held_by, _pid} = Config.acquire_lock(home)
      assert File.read!(Path.join(dir, "owner.json")) == owner_before

      Config.release_lock(home, token)
    end

    test "concurrent acquire_lock/1 contenders on a fresh path -- never more than one holder" do
      home = tmp_home()

      results =
        1..16
        |> Enum.map(fn _ -> Task.async(fn -> Config.acquire_lock(home) end) end)
        |> Enum.map(&Task.await(&1, 10_000))

      successes = Enum.filter(results, &match?({:ok, _token}, &1))

      assert length(successes) == 1

      case successes do
        [{:ok, token}] -> Config.release_lock(home, token)
        [] -> :ok
      end
    end
  end

