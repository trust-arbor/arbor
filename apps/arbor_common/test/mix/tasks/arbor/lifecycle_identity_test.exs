    end

    test "metadata stale (dead pid) -> already_stopped, cleans up both files" do
      meta = %{node: @node, host: "127.0.0.1", pid: 42, state: :ready}
      facts = %{metadata: {:ok, meta}, metadata_pid_check: :no_such_process}
      assert {:already_stopped, [:pid_file, :metadata_file]} = Identity.decide_stop(facts)
    end

    test "metadata pid reused -> already_stopped, cleans up both files" do
      meta = %{node: @node, host: "127.0.0.1", pid: 42, state: :ready}
      facts = %{metadata: {:ok, meta}, metadata_pid_check: :present_not_arbor}
      assert {:already_stopped, [:pid_file, :metadata_file]} = Identity.decide_stop(facts)
    end

    test "security regression: malformed canonical metadata is ambiguous, never falls back to legacy or already_stopped" do
      # Canonical metadata exists but is corrupted -- distinct from :absent.
      # A prior version of this decision treated {:error, :malformed} the
      # same as :absent and fell through to the legacy-PID branch, which
      # could report already_stopped (silently green-lighting Restart to
      # launch a second daemon) or signal an unrelated legacy PID while a
      # real canonically-tracked daemon might still be alive. Even a legacy
      # PID that verifies as alive must not override this: malformed
      # canonical evidence is ambiguous on its own.
      facts = %{
        metadata: {:error, :malformed},
        legacy_pid_present?: true,
        legacy_pid: 77,
        legacy_pid_check: {:verified_arbor, @node},
        node_ping: :pang
      }

      assert {:ambiguous, %{reason: :malformed_canonical_metadata}} = Identity.decide_stop(facts)
    end

    test "malformed canonical metadata, no legacy pid -> still ambiguous, never already_stopped" do
      facts = %{metadata: {:error, :malformed}, legacy_pid_present?: false}
      assert {:ambiguous, %{reason: :malformed_canonical_metadata}} = Identity.decide_stop(facts)
    end

    test "absent metadata, legacy stale -> already_stopped, cleans up only the pid file" do
      facts = %{
        metadata: :absent,
        legacy_pid_present?: true,
        legacy_pid: 77,
        legacy_pid_check: :no_such_process
      }

      assert {:already_stopped, [:pid_file]} = Identity.decide_stop(facts)
    end

    test "absent metadata, legacy unverified -> ambiguous, never signals" do
      facts = %{
        metadata: :absent,
        legacy_pid_present?: true,
        legacy_pid: 77,
        legacy_pid_check: :unverified
      }

      assert {:ambiguous, %{reason: :ambiguous_legacy_state}} = Identity.decide_stop(facts)
    end

    test "absent metadata, no legacy pid -> already_stopped, nothing to clean up" do
      facts = %{metadata: :absent, legacy_pid_present?: false}
      assert {:already_stopped, []} = Identity.decide_stop(facts)
    end
  end

