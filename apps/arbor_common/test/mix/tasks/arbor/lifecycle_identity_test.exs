  # A throwaway per-test directory so boundary tests never touch the real
  # ~/.arbor. Never used to signal anything; only ever read/written as plain
  # files, and cleaned up on exit.
  defp tmp_home do
    dir =
      Path.join(System.tmp_dir!(), "arbor_lifecycle_test_#{System.unique_integer([:positive])}")

    File.mkdir_p!(dir)
    on_exit(fn -> File.rm_rf!(dir) end)
    dir
  end

  # The test process's own OS pid: genuinely alive, and genuinely not an
  # Arbor node (its argv never matches `-name`/`-sname arbor_dev_<hex>@...`),
  # so every boundary test that reaches a real signal-authorization check
  # deterministically lands on the refused/preserve-evidence branch. No
  # test in this file ever exercises the safe-to-signal branch against a
  # real process.
  defp self_pid, do: System.pid() |> String.to_integer()

  # -- parse_metadata / encode_metadata -------------------------------------

  describe "parse_metadata/1" do
    test "accepts a well-formed record" do
      raw = Jason.encode!(%{version: 1, node: @node, host: "127.0.0.1", pid: 123, state: "ready"})

      assert {:ok, %{node: @node, host: "127.0.0.1", pid: 123, state: :ready}} =
               Identity.parse_metadata(raw)
    end

    test "rejects oversized payloads without parsing them" do
      raw =
        Jason.encode!(%{
          version: 1,
          node: @node,
          host: String.duplicate("a", 5000),
          pid: 1,
          state: "ready"
