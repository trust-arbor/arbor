      assert {:error, :malformed} = Identity.parse_metadata(raw)
    end

    test "rejects non-JSON" do
      assert {:error, :malformed} = Identity.parse_metadata("not json")
    end

    test "rejects wrong version" do
      raw = Jason.encode!(%{version: 2, node: @node, host: "127.0.0.1", pid: 1, state: "ready"})
      assert {:error, :malformed} = Identity.parse_metadata(raw)
    end

    test "rejects malformed node shape" do
      raw =
        Jason.encode!(%{
          version: 1,
          node: "not-a-node",
          host: "127.0.0.1",
