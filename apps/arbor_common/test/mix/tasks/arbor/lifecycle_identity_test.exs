  # -- Start.track_launch/4 tracking-transaction regressions ----------------

  describe "Start.track_launch/4 tracking-transaction regressions" do
    test "legacy write fails, metadata succeeds -> :ok, warns visibly, canonical evidence present, nothing signaled" do
      home = tmp_home()
      pid = self_pid()
      # A validly-shaped node string (real local node_id, so it round-trips
      # through read_metadata's identity cross-check) -- unlike @foreign_node,
      # which is deliberately shape-invalid for the argv-parsing tests above.
      node_string = "arbor_dev_#{Config.node_id()}@127.0.0.1"
      # Force the legacy pid-file write to fail: a directory sits where the
      # pid file must be written.
      File.mkdir_p!(Config.pid_file(home))

      stderr =
        ExUnit.CaptureIO.capture_io(:stderr, fn ->
          assert :ok = Start.track_launch(node_string, "127.0.0.1", pid, home)
        end)

      # Operator-visible warning required: a legacy-write failure tolerated
      # because canonical metadata succeeded must never be silent -- the
      # operator needs to know legacy-only fallback tooling has nothing to
      # find for this daemon.
      assert stderr =~ "Warning: failed to write the legacy PID file"
      assert stderr =~ Config.pid_file(home)

      assert {:ok, %{node: ^node_string}} = Config.read_metadata(home)
      assert {:error, :malformed} = Config.read_pid(home)
      assert Config.pid_alive?(pid)
    end

    test "metadata write fails, legacy evidence preserved -> signal_if_verified invoked and refused, exits" do
      home = tmp_home()
      pid = self_pid()
      # Force the metadata write to fail: a directory sits where
      # write_metadata!/2's File.rename! must land.
      File.mkdir_p!(Config.metadata_file(home))

      assert catch_exit(Start.track_launch(@foreign_node, "127.0.0.1", pid, home)) ==
               {:shutdown, 1}

      assert {:ok, ^pid} = Config.read_pid(home)
      assert Config.pid_alive?(pid)
    end

    test "dual write failure -> no evidence exists, signal_if_verified invoked and refused, exits" do
      home = tmp_home()
      pid = self_pid()
      File.mkdir_p!(Config.pid_file(home))
      File.mkdir_p!(Config.metadata_file(home))

      assert catch_exit(Start.track_launch(@foreign_node, "127.0.0.1", pid, home)) ==
               {:shutdown, 1}

      assert {:error, :malformed} = Config.read_pid(home)
      assert {:error, :malformed} = Config.read_metadata(home)
      assert Config.pid_alive?(pid)
    end
  end

